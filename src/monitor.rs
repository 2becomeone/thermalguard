use std::collections::VecDeque;

use crate::config::{Config, SensorThresholds};

/// Hardware component category.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum SensorKind {
    Cpu,
    Gpu,
}

impl SensorKind {
    pub fn label(self) -> &'static str {
        match self {
            SensorKind::Cpu => "CPU",
            SensorKind::Gpu => "GPU",
        }
    }
}

/// Snapshot of a single thermal sensor reading.
#[derive(Debug, Clone)]
pub struct SensorReading {
    pub kind: SensorKind,
    pub name: String,
    pub source: String,
    pub temp_c: f32,
    pub throttle_limit_c: Option<f32>,
    pub is_throttling: bool,
    pub throttle_reason: Option<String>,
    pub fan_percent: Option<u32>,
}

/// Alert severity mapped to Windows notification icon & sound behavior.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum AlertSeverity {
    Info,
    Warning,
    Critical,
}

/// Classification of a thermal event.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum AlertKind {
    ThermalThrottling,
    Overheating,
    HeatingUpQuickly,
    HighTemp,
    CooledDown,
}

/// User-facing notification generated by `AlertEngine`.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Alert {
    pub sensor: SensorKind,
    pub kind: AlertKind,
    pub severity: AlertSeverity,
    pub title: String,
    pub body: String,
}

/// Aggregate thermal health status used for tray icon color and tooltip.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum OverallStatus {
    Normal,
    Warning,
    RapidRise,
    Critical,
    Paused,
}

impl OverallStatus {
    pub fn label(self) -> &'static str {
        match self {
            OverallStatus::Normal => "Normal",
            OverallStatus::Warning => "High Temp",
            OverallStatus::RapidRise => "Heating Up Quickly",
            OverallStatus::Critical => "Overheating / Throttling",
            OverallStatus::Paused => "Paused",
        }
    }
}

#[derive(Debug, Default)]
struct SensorTracker {
    samples: VecDeque<(u64, f32)>,
    warn_since_ms: Option<u64>,
    cool_since_ms: Option<u64>,
    in_warn: bool,
    in_critical: bool,
    was_hot: bool,
    last_throttle_alert_ms: Option<u64>,
    last_critical_alert_ms: Option<u64>,
    last_rapid_rise_alert_ms: Option<u64>,
    last_warn_alert_ms: Option<u64>,
}

impl SensorTracker {
    fn reset(&mut self) {
        *self = Self::default();
    }

    fn push_sample(&mut self, now_ms: u64, temp_c: f32, window_ms: u64) {
        if let Some(&(last_t, _)) = self.samples.back() {
            if now_ms < last_t {
                // Clock stepped backward; clear stale history.
                self.samples.clear();
            }
        }
        self.samples.push_back((now_ms, temp_c));

        let retain_ms = (window_ms.saturating_add(5_000)).max(30_000);
        while let Some(&(oldest_t, _)) = self.samples.front() {
            if now_ms.saturating_sub(oldest_t) > retain_ms {
                self.samples.pop_front();
            } else {
                break;
            }
        }
    }

    /// Computes smoothed temperature rise over `window_ms` by comparing the mean of up to 2
    /// newest samples against the mean of up to 2 baseline samples closest to `now_ms - window_ms`.
    fn compute_rise(&self, now_ms: u64, window_ms: u64) -> Option<(f32, f32)> {
        let len = self.samples.len();
        if len < 3 {
            return None;
        }
        let first_t = self.samples.front()?.0;
        let last_t = self.samples.back()?.0;
        if last_t.saturating_sub(first_t) < window_ms / 2 {
            return None;
        }

        let recent_start = len.saturating_sub(2);
        let recent_slice = self.samples.range(recent_start..len);
        let mut recent_sum = 0.0_f32;
        let mut recent_t_sum = 0.0_f64;
        let mut recent_cnt = 0_usize;
        for &(t, temp) in recent_slice {
            recent_sum += temp;
            recent_t_sum += t as f64;
            recent_cnt += 1;
        }
        let recent_mean = recent_sum / recent_cnt as f32;
        let recent_mean_t = recent_t_sum / recent_cnt as f64;

        let target_t = now_ms.saturating_sub(window_ms);
        let candidate_end = recent_start;
        if candidate_end == 0 {
            return None;
        }

        let mut candidates: Vec<(u64, u64, f32)> = self
            .samples
            .range(0..candidate_end)
            .map(|&(t, temp)| (t.abs_diff(target_t), t, temp))
            .collect();
        candidates.sort_by_key(|&(dist, t, _)| (dist, t));

        let base_take = candidates.len().min(2);
        let mut base_sum = 0.0_f32;
        let mut base_t_sum = 0.0_f64;
        for &(_, t, temp) in &candidates[..base_take] {
            base_sum += temp;
            base_t_sum += t as f64;
        }
        let base_mean = base_sum / base_take as f32;
        let base_mean_t = base_t_sum / base_take as f64;

        let dt_ms = recent_mean_t - base_mean_t;
        if dt_ms < 500.0 {
            return None;
        }

        let delta_c = recent_mean - base_mean;
        let rate_c_per_sec = delta_c / (dt_ms as f32 / 1000.0);
        Some((delta_c, rate_c_per_sec))
    }

    #[allow(clippy::too_many_arguments)]
    fn evaluate(
        &mut self,
        now_ms: u64,
        reading: &SensorReading,
        thresholds: &SensorThresholds,
        hysteresis_c: f32,
        warn_sustain_ms: u64,
        notify_cooldown: bool,
    ) -> (Option<Alert>, SensorStateKind) {
        let window_ms = thresholds.rapid_rise_window_secs * 1000;
        self.push_sample(now_ms, reading.temp_c, window_ms);

        let effective_critical_c = match reading.throttle_limit_c {
            Some(lim) => thresholds.critical_c.min((lim - 3.0).max(55.0)),
            None => thresholds.critical_c,
        };

        // Update hysteresis state flags continuously regardless of which alert fires.
        if reading.temp_c >= effective_critical_c {
            self.in_critical = true;
        } else if reading.temp_c <= effective_critical_c - hysteresis_c {
            self.in_critical = false;
        }

        if reading.temp_c >= thresholds.warn_c {
            if self.warn_since_ms.is_none() {
                self.warn_since_ms = Some(now_ms);
            }
        } else if reading.temp_c <= thresholds.warn_c - hysteresis_c {
            self.warn_since_ms = None;
            self.in_warn = false;
        }

        if reading.is_throttling || reading.temp_c > thresholds.warn_c - hysteresis_c {
            self.cool_since_ms = None;
        }

        let rise = self.compute_rise(now_ms, window_ms);
        let is_rapid_rise = rise.is_some_and(|(delta_c, _)| {
            !self.in_critical
                && reading.temp_c >= thresholds.rapid_rise_min_temp_c
                && delta_c >= thresholds.rapid_rise_delta_c
        });

        let state = if reading.is_throttling || self.in_critical {
            SensorStateKind::Critical
        } else if is_rapid_rise {
            SensorStateKind::RapidRise
        } else if self.in_warn || reading.temp_c >= thresholds.warn_c {
            SensorStateKind::Warning
        } else {
            SensorStateKind::Normal
        };

        let label = reading.kind.label();
        let fan_suffix = reading
            .fan_percent
            .map(|f| format!(" (fan {f}%)"))
            .unwrap_or_default();

        // 1. Hardware Thermal Throttling
        if reading.is_throttling {
            self.was_hot = true;
            if cooldown_ready(
                self.last_throttle_alert_ms,
                now_ms,
                thresholds.critical_cooldown_secs * 1000,
            ) {
                self.last_throttle_alert_ms = Some(now_ms);
                let reason = reading
                    .throttle_reason
                    .as_deref()
                    .unwrap_or("Hardware thermal slowdown active");
                return (
                    Some(Alert {
                        sensor: reading.kind,
                        kind: AlertKind::ThermalThrottling,
                        severity: AlertSeverity::Critical,
                        title: format!("{label} THERMAL THROTTLING! ({:.0}°C)", reading.temp_c),
                        body: format!(
                            "{}: {reason}{fan_suffix}. Clocks are being reduced to protect hardware.",
                            reading.name
                        ),
                    }),
                    state,
                );
            }
            return (None, state);
        }

        // 2. Critical Overheating
        if reading.temp_c >= effective_critical_c {
            self.was_hot = true;
            if cooldown_ready(
                self.last_critical_alert_ms,
                now_ms,
                thresholds.critical_cooldown_secs * 1000,
            ) {
                self.last_critical_alert_ms = Some(now_ms);
                let limit_note = match reading.throttle_limit_c {
                    Some(lim) => format!(" (throttle limit {lim:.0}°C)"),
                    None => format!(" (critical {effective_critical_c:.0}°C)"),
                };
                return (
                    Some(Alert {
                        sensor: reading.kind,
                        kind: AlertKind::Overheating,
                        severity: AlertSeverity::Critical,
                        title: format!("{label} OVERHEATING! ({:.0}°C)", reading.temp_c),
                        body: format!(
                            "{} hit {:.0}°C{limit_note}{fan_suffix} — thermal throttling imminent!",
                            reading.name, reading.temp_c
                        ),
                    }),
                    state,
                );
            }
            return (None, state);
        }

        // 3. Heating Up Quickly
        if is_rapid_rise {
            self.was_hot = true;
            if let Some((delta_c, rate)) = rise {
                if cooldown_ready(
                    self.last_rapid_rise_alert_ms,
                    now_ms,
                    thresholds.rapid_rise_cooldown_secs * 1000,
                ) {
                    self.last_rapid_rise_alert_ms = Some(now_ms);
                    let eta_part = if rate > 0.05 && reading.temp_c < effective_critical_c {
                        let eta_secs = ((effective_critical_c - reading.temp_c) / rate)
                            .ceil()
                            .max(1.0) as u64;
                        format!(", ~{eta_secs}s to {effective_critical_c:.0}°C critical")
                    } else {
                        String::new()
                    };
                    return (
                        Some(Alert {
                            sensor: reading.kind,
                            kind: AlertKind::HeatingUpQuickly,
                            severity: AlertSeverity::Warning,
                            title: format!("{label} Heating Up Quickly! ({:.0}°C)", reading.temp_c),
                            body: format!(
                                "{} rose +{delta_c:.1}°C in {}s ({rate:.1}°C/s{eta_part}){fan_suffix}.",
                                reading.name, thresholds.rapid_rise_window_secs
                            ),
                        }),
                        state,
                    );
                }
            }
            return (None, state);
        }

        // 4. High Sustained Temperature
        if reading.temp_c >= thresholds.warn_c {
            let sustained = self
                .warn_since_ms
                .is_some_and(|since| now_ms.saturating_sub(since) >= warn_sustain_ms);
            if sustained {
                self.in_warn = true;
                self.was_hot = true;
                if cooldown_ready(
                    self.last_warn_alert_ms,
                    now_ms,
                    thresholds.warn_cooldown_secs * 1000,
                ) {
                    self.last_warn_alert_ms = Some(now_ms);
                    let headroom = reading
                        .throttle_limit_c
                        .map(|lim| format!(", {:.0}°C below throttle limit", (lim - reading.temp_c).max(0.0)))
                        .unwrap_or_default();
                    return (
                        Some(Alert {
                            sensor: reading.kind,
                            kind: AlertKind::HighTemp,
                            severity: AlertSeverity::Warning,
                            title: format!("{label} High Temperature ({:.0}°C)", reading.temp_c),
                            body: format!(
                                "{} is running hot at {:.0}°C (warn {:.0}°C{headroom}){fan_suffix}.",
                                reading.name, reading.temp_c, thresholds.warn_c
                            ),
                        }),
                        state,
                    );
                }
            }
            return (None, state);
        }

        // 5. Cooled Down Recovery Notice
        if notify_cooldown
            && self.was_hot
            && !reading.is_throttling
            && reading.temp_c <= thresholds.warn_c - hysteresis_c
        {
            let since = *self.cool_since_ms.get_or_insert(now_ms);
            if now_ms.saturating_sub(since) >= 5_000 {
                self.was_hot = false;
                self.cool_since_ms = None;
                return (
                    Some(Alert {
                        sensor: reading.kind,
                        kind: AlertKind::CooledDown,
                        severity: AlertSeverity::Info,
                        title: format!("{label} Cooled Down ({:.0}°C)", reading.temp_c),
                        body: format!(
                            "{} returned to normal temperature ({:.0}°C).",
                            reading.name, reading.temp_c
                        ),
                    }),
                    state,
                );
            }
        }

        (None, state)
    }
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum SensorStateKind {
    Normal,
    Warning,
    RapidRise,
    Critical,
}

fn cooldown_ready(last_ms: Option<u64>, now_ms: u64, cooldown_ms: u64) -> bool {
    match last_ms {
        None => true,
        Some(prev) => now_ms.saturating_sub(prev) >= cooldown_ms,
    }
}

/// Evaluates CPU and GPU readings and emits deduplicated thermal alerts.
pub struct AlertEngine {
    config: Config,
    cpu: SensorTracker,
    gpu: SensorTracker,
}

impl AlertEngine {
    pub fn new(config: Config) -> Self {
        Self {
            config,
            cpu: SensorTracker::default(),
            gpu: SensorTracker::default(),
        }
    }

    pub fn update_config(&mut self, config: Config) {
        self.config = config;
    }

    pub fn reset(&mut self) {
        self.cpu.reset();
        self.gpu.reset();
    }

    pub fn config(&self) -> &Config {
        &self.config
    }

    pub fn evaluate(&mut self, now_ms: u64, readings: &[SensorReading]) -> (Vec<Alert>, OverallStatus) {
        let mut alerts = Vec::new();
        let mut worst = SensorStateKind::Normal;

        for reading in readings {
            if !reading.temp_c.is_finite() {
                continue;
            }
            let (thresholds, tracker) = match reading.kind {
                SensorKind::Cpu => (&self.config.cpu, &mut self.cpu),
                SensorKind::Gpu => (&self.config.gpu, &mut self.gpu),
            };
            if !thresholds.enabled {
                continue;
            }

            let (alert, state) = tracker.evaluate(
                now_ms,
                reading,
                thresholds,
                self.config.hysteresis_c,
                self.config.warn_sustain_secs * 1000,
                self.config.notify_cooldown,
            );
            if let Some(a) = alert {
                alerts.push(a);
            }
            worst = max_state(worst, state);
        }

        let overall = match worst {
            SensorStateKind::Normal => OverallStatus::Normal,
            SensorStateKind::Warning => OverallStatus::Warning,
            SensorStateKind::RapidRise => OverallStatus::RapidRise,
            SensorStateKind::Critical => OverallStatus::Critical,
        };

        (alerts, overall)
    }
}

fn max_state(a: SensorStateKind, b: SensorStateKind) -> SensorStateKind {
    use SensorStateKind::*;
    match (a, b) {
        (Critical, _) | (_, Critical) => Critical,
        (RapidRise, _) | (_, RapidRise) => RapidRise,
        (Warning, _) | (_, Warning) => Warning,
        _ => Normal,
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn cpu_reading(temp_c: f32) -> SensorReading {
        SensorReading {
            kind: SensorKind::Cpu,
            name: "Intel Core i5-13600KF".to_string(),
            source: "PawnIO MSR".to_string(),
            temp_c,
            throttle_limit_c: Some(100.0),
            is_throttling: false,
            throttle_reason: None,
            fan_percent: None,
        }
    }

    fn gpu_reading(temp_c: f32) -> SensorReading {
        SensorReading {
            kind: SensorKind::Gpu,
            name: "RTX 5060 Ti".to_string(),
            source: "NVML".to_string(),
            temp_c,
            throttle_limit_c: Some(87.0),
            is_throttling: false,
            throttle_reason: None,
            fan_percent: Some(45),
        }
    }

    #[test]
    fn normal_temps_produce_no_alerts() {
        let mut engine = AlertEngine::new(Config::default());
        for i in 0..10 {
            let (alerts, status) =
                engine.evaluate(i * 1000, &[cpu_reading(45.0 + (i % 3) as f32), gpu_reading(42.0)]);
            assert!(alerts.is_empty());
            assert_eq!(status, OverallStatus::Normal);
        }
    }

    #[test]
    fn idle_spike_below_min_temp_floor_does_not_alert() {
        let mut engine = AlertEngine::new(Config::default());
        let temps = [35.0, 36.0, 46.0, 55.0];
        for (i, &t) in temps.iter().enumerate() {
            let (alerts, status) = engine.evaluate(i as u64 * 1000, &[cpu_reading(t)]);
            assert!(alerts.is_empty(), "unexpected alert at {t}°C: {alerts:?}");
            assert_eq!(status, OverallStatus::Normal);
        }
    }

    #[test]
    fn rapid_spike_above_floor_fires_once_with_eta_and_respects_cooldown() {
        let mut engine = AlertEngine::new(Config::default());
        // 66 -> 80 in 4 seconds (CPU rapid_rise_delta_c = 12, min_temp_c = 65)
        let sequence = [(0, 66.0), (1000, 66.0), (2000, 74.0), (3000, 79.0), (4000, 80.0)];
        let mut triggered = Vec::new();
        for &(ts, temp) in &sequence {
            let (alerts, _) = engine.evaluate(ts, &[cpu_reading(temp)]);
            triggered.extend(alerts);
        }
        assert_eq!(triggered.len(), 1);
        assert_eq!(triggered[0].kind, AlertKind::HeatingUpQuickly);
        assert_eq!(triggered[0].severity, AlertSeverity::Warning);
        assert!(
            triggered[0].body.contains("to 90°C critical"),
            "expected ETA in body: {}",
            triggered[0].body
        );

        // Next second still rapidly rising -> suppressed by 45s cooldown
        let (alerts_suppressed, status) = engine.evaluate(5000, &[cpu_reading(82.0)]);
        assert!(alerts_suppressed.is_empty());
        assert_eq!(status, OverallStatus::RapidRise);
    }

    #[test]
    fn high_temp_sustain_hysteresis_and_cooldown_recovery() {
        let mut engine = AlertEngine::new(Config::default());

        // Below 3s sustain -> no alert yet
        let (a0, _) = engine.evaluate(0, &[cpu_reading(81.0)]);
        assert!(a0.is_empty());
        let (a1, _) = engine.evaluate(2000, &[cpu_reading(81.0)]);
        assert!(a1.is_empty());

        // At 3s sustain -> HighTemp fires
        let (a2, s2) = engine.evaluate(3000, &[cpu_reading(81.0)]);
        assert_eq!(a2.len(), 1);
        assert_eq!(a2[0].kind, AlertKind::HighTemp);
        assert_eq!(s2, OverallStatus::Warning);

        // Drops to 79°C (inside 5°C hysteresis band: 80 - 5 = 75°C) then back to 80°C -> no flap or re-alert
        let (a3, s3) = engine.evaluate(4000, &[cpu_reading(79.0)]);
        assert!(a3.is_empty());
        assert_eq!(s3, OverallStatus::Warning);
        let (a4, s4) = engine.evaluate(5000, &[cpu_reading(80.0)]);
        assert!(a4.is_empty());
        assert_eq!(s4, OverallStatus::Warning);

        // Drops to 74°C (<= 75°C) and holds for 5s -> CooledDown fires once
        let (a5, s5) = engine.evaluate(10_000, &[cpu_reading(74.0)]);
        assert!(a5.is_empty());
        assert_eq!(s5, OverallStatus::Normal);
        let (a6, _) = engine.evaluate(14_000, &[cpu_reading(74.0)]);
        assert!(a6.is_empty());
        let (a7, _) = engine.evaluate(15_000, &[cpu_reading(74.0)]);
        assert_eq!(a7.len(), 1);
        assert_eq!(a7[0].kind, AlertKind::CooledDown);
        assert_eq!(a7[0].severity, AlertSeverity::Info);

        // Stays cool -> no second CooledDown
        let (a8, _) = engine.evaluate(25_000, &[cpu_reading(70.0)]);
        assert!(a8.is_empty());
    }

    #[test]
    fn overheating_fires_immediately_and_realerts_after_cooldown() {
        let mut engine = AlertEngine::new(Config::default());

        let (a0, s0) = engine.evaluate(0, &[cpu_reading(91.0)]);
        assert_eq!(a0.len(), 1);
        assert_eq!(a0[0].kind, AlertKind::Overheating);
        assert_eq!(a0[0].severity, AlertSeverity::Critical);
        assert_eq!(s0, OverallStatus::Critical);

        // Still hot before 30s cooldown -> suppressed
        let (a1, s1) = engine.evaluate(29_000, &[cpu_reading(91.0)]);
        assert!(a1.is_empty());
        assert_eq!(s1, OverallStatus::Critical);

        // At 30s -> re-alerts
        let (a2, _) = engine.evaluate(30_000, &[cpu_reading(92.0)]);
        assert_eq!(a2.len(), 1);
        assert_eq!(a2[0].kind, AlertKind::Overheating);
    }

    #[test]
    fn hardware_throttling_fires_immediately_even_below_critical_threshold() {
        let mut engine = AlertEngine::new(Config::default());
        let mut r = gpu_reading(72.0);
        r.is_throttling = true;
        r.throttle_reason = Some("HW Thermal Slowdown".to_string());

        let (alerts, status) = engine.evaluate(0, &[r]);
        assert_eq!(alerts.len(), 1);
        assert_eq!(alerts[0].kind, AlertKind::ThermalThrottling);
        assert_eq!(alerts[0].severity, AlertSeverity::Critical);
        assert_eq!(status, OverallStatus::Critical);
    }

    #[test]
    fn dynamic_throttle_limit_lowers_effective_critical_threshold() {
        let mut engine = AlertEngine::new(Config::default());
        // GPU default critical_c is 83.0; if throttle_limit_c is 80.0, effective_critical_c = 77.0.
        let mut r = gpu_reading(78.0);
        r.throttle_limit_c = Some(80.0);

        let (alerts, status) = engine.evaluate(0, &[r]);
        assert_eq!(alerts.len(), 1);
        assert_eq!(alerts[0].kind, AlertKind::Overheating);
        assert_eq!(status, OverallStatus::Critical);
    }
}
